const _wger = 'https://wger.de/media/exercise-images/';
const _wgerVideo = 'https://wger.de/media/exercise-video/';

class SeedExercise {
  const SeedExercise({
    required this.key,
    required this.name,
    required this.muscle,
    this.secondary = const [],
    required this.equipment,
    required this.level,
    required this.type,
    required this.description,
    required this.steps,
    required this.mistakes,
    required this.breathing,
    this.images = const [],
    this.youtube,
    this.video,
    this.wgerId,
    required this.author,
  });

  final String key;
  final String name;
  final Muscle muscle;
  final List<Muscle> secondary;
  final Equipment equipment;
  final Level level;
  final ExerciseType type;
  final String description;
  final List<String> steps;
  final List<String> mistakes;
  final String breathing;
  final List<String> images;
  final String? youtube;
  final String? video;
  final int? wgerId;

  /// Clé du coach auteur (`admin`, `amira`, `mehdi`, `sarra`).
  final String author;

  Exercise build(String authorId, DateTime createdAt) => Exercise(
    id: 'ex_$key',
    name: name,
    primaryMuscle: muscle,
    secondaryMuscles: secondary,
    equipment: equipment,
    level: level,
    type: type,
    description: description,
    steps: steps,
    mistakes: mistakes,
    breathing: breathing,
    media: [
      for (final i in images) MediaItem(kind: MediaKind.image, source: '$_wger$i'),
      if (video != null)
        MediaItem(
          kind: MediaKind.video,
          source: '$_wgerVideo$video',
          caption: 'Démonstration wger (CC-BY-SA)',
        ),
      if (youtube != null)
        MediaItem(
          kind: MediaKind.youtube,
          source: youtube!,
          caption: 'Tutoriel technique',
        ),
    ],
    authorId: authorId,
    createdAt: createdAt,
    wgerId: wgerId,
  );
}

